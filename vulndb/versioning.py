"""Разбор и сравнение версий.

Идея
----
Версия -- это последовательность целых чисел, разделённых точками.
Сравнивать её нужно покомпонентно и как числа, а не как строку:

    "9.0.10" > "9.0.9"   (как кортежи: (9, 0, 10) > (9, 0, 9))

но как строки "9.0.10" < "9.0.9", потому что символ "1" меньше "9".

SQLite не умеет сравнивать версии, поэтому каждую версию превращаем
в *ключ сортировки* -- строку, у которой обычное строковое сравнение
совпадает с числовым сравнением версий.

Как строится ключ
-----------------
1. Версия разбирается в кортеж чисел:        "9.0.10" -> (9, 0, 10)
2. Кортеж дополняется нулями до MAX_PARTS:   (9, 0, 10) -> (9, 0, 10, 0, 0, 0)
3. Каждое число дополняется нулями слева
   до COMPONENT_WIDTH цифр и склеивается точками.

Шаг 2 даёт равенство "15" == "15.0.0" (отсутствующий компонент -- ноль).
Шаг 3 гарантирует, что внутри компонента строковый порядок совпадает с
числовым (все строки одной длины).
"""

from __future__ import annotations

import re

# Максимальное число компонентов. В исходных данных их не больше 4;
# с запасом берём 6.
MAX_PARTS = 6

# Максимальное число цифр в одном компоненте. Самый длинный компонент
# в данных -- 5 цифр (например, 30514 в 20.005.30514); берём 10.
COMPONENT_WIDTH = 10

# fullmatch + явный диапазон [0-9]: не принимаем юникодные цифры
# (например, арабо-индийские) и хвостовой перевод строки.
_VERSION_RE = re.compile(r"[0-9]+(?:\.[0-9]+)*")


class InvalidVersionError(ValueError):
    """Строка не является корректной версией."""


def parse_version(text: str) -> tuple[int, ...]:
    """Разбирает версию в кортеж целых чисел.

    >>> parse_version("9.0.10")
    (9, 0, 10)
    >>> parse_version("20.005.30514")   # ведущие нули отбрасываются
    (20, 5, 30514)

    Бросает InvalidVersionError для всего, что не похоже на
    «числа через точку»: пустая строка, "1.2.x", "1..2", "v1.0", "-1".
    """
    if not isinstance(text, str):
        raise InvalidVersionError(f"версия должна быть строкой, получено {type(text).__name__}")

    value = text.strip()
    if not _VERSION_RE.fullmatch(value):
        raise InvalidVersionError(
            f"некорректная версия {text!r}: ожидаются числа, разделённые точками (например, 2.4.1)"
        )

    parts = tuple(int(p) for p in value.split("."))

    if len(parts) > MAX_PARTS:
        raise InvalidVersionError(
            f"в версии {text!r} {len(parts)} компонентов, поддерживается не больше {MAX_PARTS}"
        )
    too_big = [p for p in parts if len(str(p)) > COMPONENT_WIDTH]
    if too_big:
        raise InvalidVersionError(
            f"в версии {text!r} есть компонент длиннее {COMPONENT_WIDTH} цифр"
        )
    return parts


def make_key(text: str) -> str:
    """Возвращает ключ сортировки: строковый порядок == порядок версий.

    >>> make_key("9.0.10")
    '0000000009.0000000000.0000000010.0000000000.0000000000.0000000000'
    >>> make_key("15") == make_key("15.0.0")
    True
    """
    parts = parse_version(text)
    padded = parts + (0,) * (MAX_PARTS - len(parts))
    return ".".join(str(p).zfill(COMPONENT_WIDTH) for p in padded)
